#!/usr/bin/env python3
"""Generate tables.go: the Windows code pages, and Mac Roman, in Unicode.

  python3 internal/codepage/generate.py     # needs curl

Source: Microsoft's tables of its code pages, as the Unicode Consortium
publishes them (https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/),
fetched and checked by hash. They are Unicode Data Files under the
Unicode License V3; see NOTICE.

A single-byte code page is 128 characters for 0x80 to 0xFF; zero is a code
the page leaves undefined. A double-byte code page (932, 936, 949, 950)
has lead bytes; for each, the characters of the trail bytes from the
lowest it has to the highest, zero where none is defined.
"""
import hashlib
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = "https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/"

SOURCES = {
    874: ("WINDOWS/CP874.TXT", "f45277e205ff5aa8f0625c52b04614bbd9d8836c142e9b90235748b0a9921ec9"),
    932: ("WINDOWS/CP932.TXT", "c9bc0b0cd42e0fbcb82a09635bb5abed86afbdd4abc9e76fa5716638217cb59f"),
    936: ("WINDOWS/CP936.TXT", "b86f601c575e9ab457380b6f7abef03c75499cc6075bdc8b4b27f3f2de74bf6a"),
    949: ("WINDOWS/CP949.TXT", "f57e6fef9d1ed44f445e319a8e1b879ce6b6064520ab571c341e47b892e32abc"),
    950: ("WINDOWS/CP950.TXT", "ed403857b05e07ecd5667c7eff6b25898cb1fefe2d06cfe718d82d631e6058b6"),
    1250: ("WINDOWS/CP1250.TXT", "e6535e3c81f4aff1a4b369c46e588a2423d6a75da341e01a6cea108c7542c19a"),
    1251: ("WINDOWS/CP1251.TXT", "d9d491808bd7956c26ef8ed07fa63015bfab32860720e07d5bf3a64a609927ee"),
    1252: ("WINDOWS/CP1252.TXT", "f607ae328b4dff5e9bfef725f5fff0ae23f38797f8a5b95998a0d2735c0e8fad"),
    1253: ("WINDOWS/CP1253.TXT", "85d917854926ef09b22abefd19c7b61494e229fa391b648dc332f1fac0879ce3"),
    1254: ("WINDOWS/CP1254.TXT", "f93569399f81abce90441793c118d2524770b58d9c5774de3233c64d88c9fca0"),
    1255: ("WINDOWS/CP1255.TXT", "67ab4e3e7c088be41e0f230fa9c2c5b9a803395bec8027a5ee77df74432290c7"),
    1256: ("WINDOWS/CP1256.TXT", "fd5835c5e3be668d4fa3dc3d0d3a6491795646fc9629c0892f45dd08aa72f367"),
    1257: ("WINDOWS/CP1257.TXT", "5ac72f382ea4f64fe61854e0dae7d311583bd1dd20797697d4dce32b175a268b"),
    1258: ("WINDOWS/CP1258.TXT", "2457d5d0fbb1d444136c579edc488d0a34474d58a36b6eb2adacba88c068df2e"),
    10000: ("MAC/ROMAN.TXT", "42eb6b483c35494d858faaf4993e80074f94d033c92029901a4913cabe0c8945"),
}


def fetch(path, digest, dest):
    subprocess.run(["curl", "-sSfL", "--max-time", "120", "-o", dest, BASE + path], check=True)
    got = hashlib.sha256(open(dest, "rb").read()).hexdigest()
    if got != digest:
        sys.exit(f"{path}: sha256 {got}, want {digest}")


def parse(path):
    """The code page's mappings, and its lead bytes."""
    single, double, leads = {}, {}, set()
    for line in open(path, encoding="latin-1"):
        line = line.split("#", 1)
        comment = line[1] if len(line) > 1 else ""
        fields = line[0].split()
        if not fields or not fields[0].startswith("0x"):
            continue  # blank, or the end-of-file mark (0x1A) one file has
        code = int(fields[0], 16)
        if len(fields) == 1:
            if "LEAD BYTE" in comment:
                leads.add(code)
            continue
        uni = int(fields[1], 16)
        if code > 0xFF:
            double[code] = uni
        else:
            single[code] = uni
    return single, double, leads


def go_runes(values, per_line=12):
    out = []
    for i in range(0, len(values), per_line):
        out.append("\t\t" + " ".join(f"0x{v:04X}," for v in values[i:i + per_line]))
    return "\n".join(out)


def main():
    pages = {}
    with tempfile.TemporaryDirectory() as tmp:
        for cp, (path, digest) in sorted(SOURCES.items()):
            dest = os.path.join(tmp, f"{cp}.txt")
            fetch(path, digest, dest)
            pages[cp] = parse(dest)
    out = ["// Code generated by generate.py from Microsoft's tables of its code pages",
           "// as the Unicode Consortium publishes them; DO NOT EDIT. See NOTICE.", "",
           "package codepage", ""]
    out.append("// singles holds the single-byte code pages: the characters of 0x80 to 0xFF.")
    out.append("var singles = map[int]*[128]uint16{")
    for cp, (single, double, leads) in sorted(pages.items()):
        if double:
            continue
        for b in range(0x80):
            if single.get(b, b) != b:
                sys.exit(f"{cp}: 0x{b:02X} is not ASCII")
        values = [single.get(b, 0) for b in range(0x80, 0x100)]
        if any(v > 0xFFFF for v in values):
            sys.exit(f"{cp}: a character outside the BMP")
        out.append(f"\t{cp}: {{\n{go_runes(values)}\n\t}},")
    out.append("}")
    out.append("")
    out.append("// doubles holds the double-byte code pages.")
    out.append("var doubles = map[int]*double{")
    for cp, (single, double, leads) in sorted(pages.items()):
        if not double:
            continue
        low = [single.get(b, 0) for b in range(0x80, 0x100)]
        runs, values = [], []
        for lead in range(0x100):
            trails = sorted(code & 0xFF for code in double if code >> 8 == lead)
            if lead not in leads or not trails:
                runs.append((0, 0, 0))
                continue
            lo, hi = trails[0], trails[-1]
            runs.append((len(values), lo, hi - lo + 1))
            values += [double.get(lead << 8 | t, 0) for t in range(lo, hi + 1)]
        if any(v > 0xFFFF for v in values + low):
            sys.exit(f"{cp}: a character outside the BMP")
        out.append(f"\t{cp}: {{")
        out.append(f"\t\tsingle: [128]uint16{{\n{go_runes(low)}\n\t\t}},")
        out.append("\t\truns: [256]run{")
        for lead, (start, lo, n) in enumerate(runs):
            if n:
                out.append(f"\t\t\t0x{lead:02X}: {{{start}, 0x{lo:02X}, {n}}},")
        out.append("\t\t},")
        out.append(f"\t\tvalues: []uint16{{\n{go_runes(values)}\n\t\t}},")
        out.append("\t},")
    out.append("}")
    path = os.path.join(HERE, "tables.go")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    subprocess.run(["gofmt", "-w", path], check=True)


if __name__ == "__main__":
    main()
