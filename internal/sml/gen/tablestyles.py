#!/usr/bin/env python3
"""Generate ../tablestyles.go: the table styles Excel has built in.

  python3 internal/sml/gen/tablestyles.py     # needs curl

A workbook names a built-in table style ("TableStyleMedium2") and does not
define it. The standard does: ECMA-376 Part 1, Annex D, whose definitions
come with the standard's download as OfficeOpenXML-SpreadsheetMLStyles.zip
→ presetTableStyles.xml. Each style is a list of formats (dxf) and of the
parts of a table they apply to. Only what a reader's eye depends on is
kept: the colour of the text and the fill behind it.

In that file an element's dxfId counts from 1, not from 0 as in a workbook;
the generator checks that every style refers to each of its formats once.
"""
import hashlib
import io
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
URL = "https://ecma-international.org/wp-content/uploads/ECMA-376-1_5th_edition_december_2016.zip"
SHA256 = "9d0bcad9cf06054785b03762fcfadbf6bab7e54a5f9d69434e34b7fd464d4129"

# The elements of a table style that apply to tables (not pivot tables),
# in the order of tableElement in tablestyles.go.
ELEMENTS = ["wholeTable", "firstColumnStripe", "secondColumnStripe", "firstRowStripe", "secondRowStripe",
            "lastColumn", "firstColumn", "headerRow", "totalRow",
            "firstHeaderCell", "lastHeaderCell", "firstTotalCell", "lastTotalCell"]


INNER_NAMES = {("TableStyleLight14", "TableStyleLight14 "), ("TableStyleDark9", "TableStyleDark9 2")}


def color(el):
    """A colorRef literal for a <color>, <fgColor> or <bgColor> element."""
    if el is None:
        return "colorRef{}"
    tint = el.get("tint")
    tail = f", tint: {float(tint)!r}" if tint else ""
    if el.get("theme") is not None:
        return f"colorRef{{kind: 3, index: {int(el.get('theme'))}{tail}}}"
    if el.get("rgb") is not None:
        v = el.get("rgb")[-6:]
        return f"colorRef{{kind: 2, rgb: theme.Color{{R: 0x{v[0:2]}, G: 0x{v[2:4]}, B: 0x{v[4:6]}}}{tail}}}"
    if el.get("indexed") is not None:
        return f"colorRef{{kind: 4, index: {int(el.get('indexed'))}{tail}}}"
    sys.exit(f"a colour of a form not expected: {el.attrib}")


def main():
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "part1.zip")
        subprocess.run(["curl", "-sSfL", "--max-time", "600", "-o", path, URL], check=True)
        got = hashlib.sha256(open(path, "rb").read()).hexdigest()
        if got != SHA256:
            sys.exit(f"sha256 {got}, want {SHA256}")
        inner = zipfile.ZipFile(io.BytesIO(zipfile.ZipFile(path).read("OfficeOpenXML-SpreadsheetMLStyles.zip")))
        root = ET.fromstring(inner.read("presetTableStyles.xml"))
    out = [
        "// Code generated by gen/tablestyles.py from ECMA-376 Part 1, Annex D",
        "// (presetTableStyles.xml); DO NOT EDIT.",
        "",
        "package sml",
        "",
        "// presetTableStyles are the table styles Excel has built in, by name: for",
        "// each element of a table that a style formats, the colour of its text and",
        "// its fill.",
        "var presetTableStyles = map[string][]presetElement{",
    ]
    count = 0
    for style in root:
        if not style.tag.startswith("TableStyle"):
            continue  # pivot table styles
        dxfs = style.find("dxfs").findall("dxf")
        ts = style.find("tableStyles").find("tableStyle")
        # The style is known by the element that holds it. Two inner names
        # differ from it in the standard's file; those are expected.
        if ts.get("name") != style.tag and (style.tag, ts.get("name")) not in INNER_NAMES:
            sys.exit(f"{style.tag}: its table style is named {ts.get('name')!r}")
        used = sorted(int(e.get("dxfId")) for e in ts.findall("tableStyleElement"))
        if used != list(range(1, len(dxfs) + 1)):
            sys.exit(f"{style.tag}: dxfIds {used} for {len(dxfs)} formats")
        out.append(f'\t"{style.tag}": {{')
        for e in ts.findall("tableStyleElement"):
            typ = e.get("type")
            if typ not in ELEMENTS:
                sys.exit(f"{style.tag}: element {typ}")
            if e.get("size") not in (None, "1"):
                sys.exit(f"{style.tag}: a stripe of size {e.get('size')}")
            dxf = dxfs[int(e.get("dxfId")) - 1]
            font = dxf.find("font")
            ink = color(font.find("color") if font is not None else None)
            fill, filled = "colorRef{}", "false"
            pf = dxf.find("fill/patternFill")
            if pf is not None:
                if pf.get("patternType", "solid") != "solid":
                    sys.exit(f"{style.tag}: a fill of pattern {pf.get('patternType')}")
                # In a format, the colour of a solid fill is its background.
                fill, filled = color(pf.find("bgColor") if pf.find("bgColor") is not None else pf.find("fgColor")), "true"
            if ink == "colorRef{}" and filled == "false":
                continue  # borders only
            out.append(f"\t\t{{element: {ELEMENTS.index(typ)}, ink: {ink}, fill: {fill}, filled: {filled}}}, // {typ}")
        out.append("\t},")
        count += 1
    out.append("}")
    if any("theme.Color" in line for line in out):
        out[4:4] = ['import "github.com/AOShei/go-fast-ooxml/internal/theme"', ""]
    with open(os.path.join(HERE, "..", "tablestyles.go"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    subprocess.run(["gofmt", "-w", os.path.join(HERE, "..", "tablestyles.go")], check=True)
    print(f"tablestyles.go written: {count} table styles")


if __name__ == "__main__":
    main()
